def _owned(cls: str) -> list[str]:
    return (
        [p for p, c, _ in FIRE if c == cls]
        + [p for p, c in R2_FIRE if c == cls]
        + [p for p, c in NEW_FIRE if c == cls]
    )


@pytest.mark.parametrize("cls", CLASSES)
def test_mutation_switching_a_class_off_loses_phrases(
    cls: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    """With one class lexicon off, phrases that only that class catches go quiet, so the tables
    above would fail without it (the older patterns alone do not satisfy them)."""
    owned = _owned(cls)
    assert len(owned) >= 3, cls
    assert all(safety.emergency(p) is not None for p in owned)
    monkeypatch.setattr(safety_lexicon, "DISABLED", {cls})
    lost = [p for p in owned if safety.emergency(p) is None]
    assert lost, f"class {cls} is not load-bearing"


