@pytest.mark.parametrize("n", [5000, 50000])
@pytest.mark.parametrize(
    "seed",
    [
        "aag ",
        "andar ",
        "mujhe ",
        "marna ",
        "bachay ",
        "zehar ",
        "koi ",
        "ka ",
        "mein aag ",
        "आग آگ fire ",
        "kha li ",
        "jal ",
        "ambulance ",
        "bachay andar mein hai ",
        "a",
    ],
)
def test_linear_time_on_adversarial_input(n: int, seed: str) -> None:
    text = (seed * (n // len(seed) + 1))[:n]
    start = time.perf_counter()
    safety_lexicon.classify(text)
    assert time.perf_counter() - start < 0.5  # the lexicon alone: about 70 ms at 50000 characters
    start = time.perf_counter()
    safety.emergency(text)
    assert time.perf_counter() - start < 2.0  # includes the older patterns (they dominate)
    start = time.perf_counter()
    safety.advice_asked(text)
    assert time.perf_counter() - start < 1.5


