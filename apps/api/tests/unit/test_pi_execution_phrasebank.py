def _all_must_not():
    return [(c, p) for c, ps in MUST_NOT.items() for p in ps]


def _all_yes():
    return [(lang, p) for lang, ps in TRUE_YES.items() for p in ps]


def test_rates_and_zero_false_approvals(capsys):
    bad = [(c, p) for c, p in _all_must_not() if classify_approval(p) is ApprovalCue.EXPLICIT_YES]
    miss = [
        (lang, p) for lang, p in _all_yes() if classify_approval(p) is not ApprovalCue.EXPLICIT_YES
    ]
    with capsys.disabled():
        print(
            f"\nphrasebank: false approvals {len(bad)}/{len(_all_must_not())}; recall {len(_all_yes()) - len(miss)}/{len(_all_yes())}"
        )
        for x in bad:
            print("  FALSE YES", x)
        for x in miss:
            print("  MISSED", x)
    assert not bad
    assert len(miss) <= len(_all_yes()) * 0.1


@pytest.mark.parametrize("cat,phrase", _all_must_not())
def test_must_not_approve(cat, phrase):
    assert classify_approval(phrase) is not ApprovalCue.EXPLICIT_YES
