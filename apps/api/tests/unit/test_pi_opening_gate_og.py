"""Platform spec v1.5 Part 18.9 / v1.6 Part 18.9, tests OG1 to OG5 (the first-reply gate), named
exactly as the spec names them. Pure checks; the model is never called."""

import re
from pathlib import Path

from app.modules.pi import fixed_lines, flow, warmup
from app.modules.pi import reply_gates as g

NEW = {"history": [], "brief": {}, "noted_problems": []}
WARM = {"warmup": {"enabled": True}, "greeting_only": True}


def test_og1() -> None:
    """A new number sending "Hello" gets a greeting and the identity question, no problem one."""
    plan = warmup.plan({**NEW, **WARM, "latest_customer_message": "Hello"})
    assert plan is not None and plan.model_writes
    assert g.opening_problem(plan.reply, NEW) is None  # the fallback line itself passes
    assert "?" in plan.reply and not g.PROBLEM_QUESTION.search(plan.reply)
    assert g.opening_problem("Hello! What's going wrong in your business?", NEW)


def test_og2() -> None:
    """The old greeting strings never appear in any reply: not in a fixed line, nor in a gate."""
    lines = [
        *flow.OPENING.values(),
        *(v for table in (warmup.IDENTITY, warmup.PAGE_ASK) for v in table.values()),
        *fixed_lines.LINES["opening"].values(),
    ]
    assert lines and not any(g.forbidden_opening(line) for line in lines)
    assert g.forbidden_opening("Tell me what's going wrong in your business and I'll start on it.")


def test_og3() -> None:
    """The first reply is generated by the model; a fixed template is a failed test."""
    plan = warmup.plan({**NEW, **WARM, "latest_customer_message": "Hello"})
    assert (
        plan is not None and plan.model_writes is True
    )  # the model writes it; the line is a fallback
    source = (Path(warmup.__file__).parent / "service_conversation.py").read_text(encoding="utf8")
    assert 'context["opening_by_model"] = True' in source
    assert "opening_fallback" in source  # the fixed line is only what a failed gate falls back to


def test_og4() -> None:
    """A known test number with FORCE_OPENING=true sees the opening."""
    old = {"history": [{"role": "ai", "text": "Hi"}], "brief": {}, "noted_problems": []}
    assert not g.is_first_reply(old)
    assert g.is_first_reply({**old, "force_opening": True})
    assert g.opening_problem("Which costs most?", {**old, "force_opening": True})


def test_og4_environment(monkeypatch) -> None:
    old = {"history": [{"role": "ai", "text": "Hi"}], "brief": {}, "noted_problems": []}
    monkeypatch.setenv("FORCE_OPENING", "true")
    assert g.is_first_reply(old)
    monkeypatch.delenv("FORCE_OPENING")
    assert not g.is_first_reply(old)


def test_og5() -> None:
    """ "My friend shared your number" is acknowledged and the identity question follows."""
    said = "My friend shared your number"
    ctx = {**NEW, "latest_customer_message": said}
    plan = warmup.plan({**ctx, **{"warmup": {"enabled": True}}})
    assert plan is not None and plan.model_writes  # a first-timer: the opening, not a problem hunt
    assert re.search(r"friend|dost", plan.reply, re.IGNORECASE)  # acknowledged in the fallback
    assert plan.reply.rstrip().endswith("?")  # then the identity question
    assert g.opening_problem(plan.reply, ctx) is None
    no_ack = "Hi, I'm pi, an AI from Workzap. What is your business called and what does it make?"
    assert "friend" in (g.opening_problem(no_ack, ctx) or "")
    ok = (
        "Hi, I'm pi, an AI from Workzap, and I'm glad your friend passed the number on. "
        "To start, what is your business called and what does it make or sell?"
    )
    assert g.opening_problem(ok, ctx) is None
    assert "friend" in g.referral_note(ctx)
    assert g.referral_note({**NEW, "latest_customer_message": "Hello"}) == ""
