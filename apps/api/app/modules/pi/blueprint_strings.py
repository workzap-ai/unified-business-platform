TABLES: dict[str, dict[str, str]] = {"en": EN, "roman_ur": RU, "ur": UR, "ar": AR}
_ALIASES = {
    "english": "en", "en-us": "en", "en-gb": "en", "en_us": "en", "en_gb": "en",
    "roman_urdu": "roman_ur", "roman-ur": "roman_ur", "roman urdu": "roman_ur", "romanurdu": "roman_ur",
    "roman-urdu": "roman_ur", "ru": "roman_ur", "ur-latn": "roman_ur",
    "urdu": "ur", "ur-pk": "ur", "ur_pk": "ur",
    "arabic": "ar", "ar-sa": "ar", "ar_sa": "ar", "ar-ae": "ar",
}  # fmt: skip


def norm_language(language: Any) -> str:
    """One of en, roman_ur, ur, ar. Anything unknown reads as English."""
    if not isinstance(language, str):
        return "en"
    key = language.strip().casefold()
    if key in TABLES:
        return key
    return _ALIASES.get(key, "en")


def tr(language: str, key: str, **kw: Any) -> str:
    """A fixed phrase in a language. A missing key or placeholder never raises: English, then the key."""
    table = TABLES.get(language) or EN
    template = table.get(key) or EN.get(key) or key
    try:
        return template.format(**kw)
    except (KeyError, IndexError, ValueError):
        return template
